// The factory's standard stays out of a project's history: only real git, real hooks and real worktrees here.
import { test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CLI = path.join(ROOT, "bin/agentic-factory.mjs");
const isLink = (p) => { try { return fs.lstatSync(p).isSymbolicLink(); } catch { return false; } };

function adopted({ before } = {}) {
  const base = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "af-std-")));
  const home = path.join(base, "home"), project = path.join(base, "project");
  fs.mkdirSync(home); fs.mkdirSync(project);
  const env = { ...process.env, HOME: home, FACTORY_SKIP_ORCA: "1" };
  for (const k of ["GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE"]) delete env[k];
  const git = (cwd, ...a) => spawnSync("git", a, { cwd, encoding: "utf8", env });
  const ok = (cwd, ...a) => { const r = git(cwd, ...a); assert.equal(r.status, 0, `git ${a.join(" ")}: ${r.stdout}${r.stderr}`); return r.stdout.trim(); };
  const cli = (cwd, ...a) => spawnSync("node", [CLI, ...a], { cwd, encoding: "utf8", env });
  ok(project, "init", "-q", "-b", "main"); ok(project, "config", "user.name", "T"); ok(project, "config", "user.email", "t@example.invalid");
  fs.writeFileSync(path.join(project, "README.md"), "x\n");
  before?.(project);
  ok(project, "add", "."); ok(project, "commit", "-qm", "initial");
  const answers = path.join(base, "answers.json");
  fs.writeFileSync(answers, JSON.stringify({ "project.name": "demo", "project.humanName": "Test Human", "agents.default": "claude", "skills.installNow": "no", "rules.confirm": "yes" }));
  const r = cli(project, "init", "--answers", answers, "--experimental-terminal-runner", "--untracked-standard");
  assert.equal(r.status, 0, r.stdout + r.stderr);
  const worktree = (name, ...rest) => { const dir = path.join(base, name); ok(project, "worktree", "add", "-q", "-b", `agents/${name}`, dir, "origin/main", ...rest); ok(dir, "config", "user.name", "T"); return dir; };
  return { base, home, project, env, git, ok, cli, answers, worktree, done: () => fs.rmSync(base, { recursive: true, force: true }) };
}

test("a project's history holds only what is its own", () => {
  const h = adopted();
  assert.deepEqual(h.ok(h.project, "ls-files").split("\n"), ["README.md", "docs/adr/0001-adopt-agentic-factory.md", "docs/debt.md", "docs/handoffs/.gitkeep", "docs/reports/.gitkeep", "docs/reviews/.gitkeep", "factory.config.json"]);
  assert.equal(fs.existsSync(path.join(h.project, ".gitignore")), false, "the project's .gitignore stays untouched");
  assert.equal(h.ok(h.project, "status", "--porcelain"), "", "nothing of the standard shows as untracked");
  assert.equal(JSON.parse(fs.readFileSync(path.join(h.project, "factory.config.json"), "utf8")).footprint, "minimal");
  for (const f of ["docs/coordinator.md", "AGENTS.factory.md", ".agents/skills/retro"]) assert.ok(isLink(path.join(h.project, f)), f);
  h.done();
});

test("every new worktree gets the standard and the hooks, and a commit cannot pick them up", () => {
  const h = adopted();
  const w = h.worktree("t1");
  for (const f of ["docs/coordinator.md", "docs/review-protocol.md", "docs/architect-protocol.md", "docs/dev-workflow.md", "AGENTS.factory.md", "CODING_STANDARDS.md", ".agents/skills/retro/SKILL.md", ".claude/skills/retro/SKILL.md"]) assert.ok(fs.existsSync(path.join(w, f)), f);
  assert.match(fs.readFileSync(path.join(w, "docs/review-protocol.md"), "utf8"), /Generated by agentic-factory/);
  assert.throws(() => fs.writeFileSync(path.join(w, "docs/coordinator.md"), "edited"), /EACCES/, "the generated handbook cannot be edited by accident");
  h.ok(w, "add", "-A");
  assert.equal(h.ok(w, "diff", "--cached", "--name-only"), "");
  // The hooks bite in the worktree, the review gate included.
  fs.writeFileSync(path.join(w, "AGENTS.md"), "# Ours\n"); h.ok(w, "add", "AGENTS.md");
  const blocked = h.git(w, "commit", "-m", "no adr");
  assert.notEqual(blocked.status, 0); assert.match(blocked.stderr, /Protected files changed/);
  h.ok(w, "reset", "-q");
  fs.rmSync(path.join(w, "AGENTS.md"));
  fs.writeFileSync(path.join(w, "app.js"), "export const a = 1;\n"); h.ok(w, "add", "app.js"); h.ok(w, "commit", "-qm", "code");
  const push = h.git(w, "push", "origin", "HEAD:main");
  assert.notEqual(push.status, 0); assert.match(push.stderr, /without a passing independent review/);
  h.done();
});

test("a tracked file at the same path is the deviation and wins", () => {
  const h = adopted();
  const r = h.cli(h.project, "deviate", "docs/review-protocol.md");
  assert.equal(r.status, 0, r.stdout + r.stderr);
  const file = path.join(h.project, "docs/review-protocol.md");
  assert.equal(isLink(file), false);
  fs.appendFileSync(file, "\nOurs.\n");
  h.ok(h.project, "add", "docs/review-protocol.md"); h.ok(h.project, "commit", "-qm", "deviate");
  assert.match(h.ok(h.project, "ls-files", "docs/review-protocol.md"), /review-protocol/);
  const u = h.cli(h.project, "update"); assert.equal(u.status, 0, u.stdout + u.stderr);
  assert.match(fs.readFileSync(file, "utf8"), /Ours\./, "update leaves the deviation alone");
  const w = path.join(h.base, "t2"); h.ok(h.project, "worktree", "add", "-q", "-b", "agents/t2", w, "HEAD");
  assert.equal(isLink(path.join(w, "docs/review-protocol.md")), false);
  assert.match(fs.readFileSync(path.join(w, "docs/review-protocol.md"), "utf8"), /Ours\./);
  assert.ok(isLink(path.join(w, "docs/coordinator.md")), "everything else stays the standard");
  assert.match(h.cli(h.project, "doctor").stdout, /deviates from the standard: docs\/review-protocol\.md/);
  assert.notEqual(h.cli(h.project, "deviate", "README.md").status, 0, "only a path of the standard can deviate");
  h.done();
});

test("someone else's clone carries nothing of the stack", () => {
  const h = adopted();
  const other = path.join(h.base, "other");
  h.ok(h.base, "clone", "-q", h.ok(h.project, "remote", "get-url", "origin"), other);
  assert.equal(fs.existsSync(path.join(other, "docs/coordinator.md")), false);
  assert.equal(fs.existsSync(path.join(other, ".agents")), false);
  assert.equal(fs.existsSync(path.join(other, "AGENTS.md")), false);
  assert.equal(h.git(other, "config", "core.hooksPath").stdout.trim(), "");
  h.done();
});

test("update removes what left the standard and keeps a clean tree", () => {
  const h = adopted();
  const exclude = path.join(h.project, ".git/info/exclude");
  const stale = path.join(h.project, "docs/retired.md");
  fs.symlinkSync(path.join(h.project, ".git/factory/files/docs/retired.md"), stale);
  fs.writeFileSync(exclude, fs.readFileSync(exclude, "utf8").replace("/docs/coordinator.md\n", "/docs/coordinator.md\n/docs/retired.md\n"));
  const own = path.join(h.project, "docs/mine.md"); fs.writeFileSync(own, "mine\n");
  const r = h.cli(h.project, "update"); assert.equal(r.status, 0, r.stdout + r.stderr);
  assert.equal(isLink(stale), false, "a link that left the standard is gone");
  assert.equal(fs.existsSync(own), true);
  assert.doesNotMatch(fs.readFileSync(exclude, "utf8"), /retired/);
  assert.equal(fs.readFileSync(exclude, "utf8").split("agentic-factory: begin").length, 2, "one managed block");
  assert.deepEqual(h.ok(h.project, "status", "--porcelain").split("\n"), ["?? docs/mine.md"]);
  h.done();
});

test("a wave re-arms what a clean or an install took away, before it pushes", () => {
  const h = adopted();
  const task = h.worktree("t3");
  fs.writeFileSync(path.join(task, "app.js"), "export const a = 1;\n"); h.ok(task, "add", "app.js"); h.ok(task, "commit", "-qm", "unreviewed code"); h.ok(task, "push", "-q", "origin", "HEAD:refs/heads/agents/t3");
  const integ = h.worktree("coordinator-integration");
  // An install that resets the hooks path, as husky's prepare script does: without re-arming, the review gate is silently off.
  const env = { ...h.env, MAIN: "main", VERIFY_CMD: "true", GATE: "env", WAVE_LOG_DIR: path.join(h.base, "logs"), INSTALL_CMD: "git config core.hooksPath /nonexistent" };
  const r = spawnSync("bash", [path.join(ROOT, "controller/integ-wave.sh"), "Wave", "summary", "origin/agents/t3"], { cwd: integ, encoding: "utf8", env });
  assert.notEqual(r.status, 0, r.stdout + r.stderr);
  assert.match(r.stdout, /PUSH-FAILED/); assert.match(r.stdout, /without a passing independent review/);
  assert.ok(isLink(path.join(integ, "docs/coordinator.md")), "the links survive the wave's clean");
  assert.equal(h.ok(h.project, "rev-parse", "origin/main"), h.ok(h.project, "rev-parse", "main"), "nothing reached main");
  h.done();
});

test("a project's own hooks stay where they are and still run first", () => {
  const h = adopted({ before: (project) => {
    fs.mkdirSync(path.join(project, ".githooks"));
    fs.writeFileSync(path.join(project, ".githooks/pre-commit"), "#!/bin/sh\necho own-hook-ran > own-hook-marker\n", { mode: 0o755 });
    spawnSync("git", ["config", "core.hooksPath", ".githooks"], { cwd: project });
  } });
  assert.equal(fs.existsSync(path.join(h.project, ".githooks/pre-commit.own")), false, "the project's file is not renamed");
  assert.ok(fs.existsSync(path.join(h.project, ".githooks/pre-commit")));
  const w = h.worktree("t4");
  fs.writeFileSync(path.join(w, "a.txt"), "a\n"); h.ok(w, "add", "a.txt"); h.ok(w, "commit", "-qm", "a");
  assert.ok(fs.existsSync(path.join(w, "own-hook-marker")));
  h.done();
});

test("a project whose .claude/skills is already a link keeps working skills", () => {
  const h = adopted({ before: (project) => {
    fs.mkdirSync(path.join(project, ".claude"));
    fs.symlinkSync("../.agents/skills", path.join(project, ".claude/skills"));
  } });
  const w = h.worktree("t5");
  for (const dir of [h.project, w]) assert.match(fs.readFileSync(path.join(dir, ".claude/skills/retro/SKILL.md"), "utf8"), /retro/i, dir);
  h.done();
});

test("keeping own hooks entirely is refused for now, without touching anything", () => {
  const base = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "af-own-")));
  spawnSync("git", ["init", "-q", "-b", "main"], { cwd: base });
  const r = spawnSync("node", [CLI, "init", "--untracked-standard", "--keep-own-hooks", "--yes"], { cwd: base, encoding: "utf8", env: { ...process.env, HOME: base, FACTORY_SKIP_ORCA: "1" } });
  assert.notEqual(r.status, 0); assert.match(r.stdout + r.stderr, /--keep-own-hooks/);
  assert.equal(fs.existsSync(path.join(base, "factory.config.json")), false);
  fs.rmSync(base, { recursive: true, force: true });
});
