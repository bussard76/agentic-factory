// The factory's standard stays out of a project's history: only real git, real hooks and real worktrees here.
import { test } from "node:test";
import assert from "node:assert/strict";
import { spawn, spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const CLI = path.join(ROOT, "bin/agentic-factory.mjs");
const isLink = (p) => { try { return fs.lstatSync(p).isSymbolicLink(); } catch { return false; } };

function adopted({ before } = {}) {
  const base = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), "af-std-")));
  const home = path.join(base, "home"), project = path.join(base, "project");
  fs.mkdirSync(home); fs.mkdirSync(project);
  const env = { ...process.env, HOME: home, FACTORY_SKIP_ORCA: "1", GIT_CONFIG_NOSYSTEM: "1" };
  for (const k of ["GIT_DIR", "GIT_WORK_TREE", "GIT_INDEX_FILE"]) delete env[k];
  const git = (cwd, ...a) => spawnSync("git", a, { cwd, encoding: "utf8", env });
  const ok = (cwd, ...a) => { const r = git(cwd, ...a); assert.equal(r.status, 0, `git ${a.join(" ")}: ${r.stdout}${r.stderr}`); return r.stdout.trim(); };
  const cli = (cwd, ...a) => spawnSync("node", [CLI, ...a], { cwd, encoding: "utf8", env });
  ok(project, "init", "-q", "-b", "main"); ok(project, "config", "user.name", "T"); ok(project, "config", "user.email", "t@example.invalid");
  fs.writeFileSync(path.join(project, "README.md"), "x\n");
  before?.(project);
  ok(project, "add", "."); ok(project, "commit", "-qm", "initial");
  const answers = path.join(base, "answers.json");
  fs.writeFileSync(answers, JSON.stringify({ "project.name": "demo", "project.humanName": "Test Human", "agents.default": "claude", "skills.installNow": "no", "rules.confirm": "yes" }));
  const r = cli(project, "init", "--answers", answers, "--experimental-terminal-runner", "--untracked-standard");
  assert.equal(r.status, 0, r.stdout + r.stderr);
  const worktree = (name, ...rest) => { const dir = path.join(base, name); ok(project, "worktree", "add", "-q", "-b", `agents/${name}`, dir, "origin/main", ...rest); ok(dir, "config", "user.name", "T"); return dir; };
  return { base, home, project, env, git, ok, cli, answers, worktree, done: () => fs.rmSync(base, { recursive: true, force: true }) };
}

test("a project's history holds only what is its own", () => {
  const h = adopted();
  assert.deepEqual(h.ok(h.project, "ls-files").split("\n"), ["README.md", "docs/adr/0001-adopt-agentic-factory.md", "docs/debt.md", "docs/handoffs/.gitkeep", "docs/reports/.gitkeep", "docs/reviews/.gitkeep", "factory.config.json"]);
  assert.equal(fs.existsSync(path.join(h.project, ".gitignore")), false, "the project's .gitignore stays untouched");
  assert.equal(h.ok(h.project, "status", "--porcelain"), "", "nothing of the standard shows as untracked");
  assert.equal(JSON.parse(fs.readFileSync(path.join(h.project, "factory.config.json"), "utf8")).footprint, "minimal");
  for (const f of ["docs/coordinator.md", "AGENTS.factory.md", ".agents/skills/retro"]) assert.ok(isLink(path.join(h.project, f)), f);
  h.done();
});

test("every new worktree gets the standard and the hooks, and a commit cannot pick them up", () => {
  const h = adopted();
  const w = h.worktree("t1");
  for (const f of ["docs/coordinator.md", "docs/review-protocol.md", "docs/architect-protocol.md", "docs/dev-workflow.md", "AGENTS.factory.md", "CODING_STANDARDS.md", ".agents/skills/retro/SKILL.md", ".claude/skills/retro/SKILL.md"]) assert.ok(fs.existsSync(path.join(w, f)), f);
  assert.match(fs.readFileSync(path.join(w, "docs/review-protocol.md"), "utf8"), /Generated by agentic-factory/);
  assert.throws(() => fs.writeFileSync(path.join(w, "docs/coordinator.md"), "edited"), /EACCES/, "the generated handbook cannot be edited by accident");
  h.ok(w, "add", "-A");
  assert.equal(h.ok(w, "diff", "--cached", "--name-only"), "");
  // The hooks bite in the worktree, the review gate included.
  fs.writeFileSync(path.join(w, "AGENTS.md"), "# Ours\n"); h.ok(w, "add", "AGENTS.md");
  const blocked = h.git(w, "commit", "-m", "no adr");
  assert.notEqual(blocked.status, 0); assert.match(blocked.stderr, /Protected files changed/);
  h.ok(w, "reset", "-q");
  fs.rmSync(path.join(w, "AGENTS.md"));
  fs.writeFileSync(path.join(w, "app.js"), "export const a = 1;\n"); h.ok(w, "add", "app.js"); h.ok(w, "commit", "-qm", "code");
  const push = h.git(w, "push", "origin", "HEAD:main");
  assert.notEqual(push.status, 0); assert.match(push.stderr, /without a passing independent review/);
  h.done();
});

